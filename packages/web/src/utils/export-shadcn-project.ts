/**
 * Extract required shadcn components from generated files
 */
function getRequiredShadcnComponentsFromFiles(result: ShadcnExportResult): string[] {
  const components = new Set<string>();

  // Parse imports from component files
  result.files.forEach((file) => {
    if (file.path.startsWith("src/components/") && file.path.endsWith(".tsx")) {
      const importMatches = file.content.matchAll(/from ["']@\/components\/ui\/([^"']+)["']/g);
      for (const match of importMatches) {
        components.add(match[1]);
      }
    }
  });

  return Array.from(components).sort();
}

/**
 * Get list of required components for display before export
 */
export function getRequiredComponents(result: ShadcnExportResult): string[] {
  return getRequiredShadcnComponentsFromFiles(result);
}
