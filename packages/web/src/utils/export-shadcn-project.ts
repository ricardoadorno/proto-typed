/**
 * Export shadcn project as ZIP file
 * Client-side only - uses browser APIs
 */

import JSZip from "jszip";
import { ShadcnExportResult } from "@proto-typed/core";

/**
 * Export shadcn project files as a ZIP download
 * Uses JSZip to create a zip file with all project files
 */
export async function exportShadcnProject(
  result: ShadcnExportResult,
  projectName: string = "proto-typed-export"
): Promise<void> {
  try {
    const zip = new JSZip();

    // Add all files to the zip
    result.files.forEach((file) => {
      zip.file(file.path, file.content);
    });

    // Add SETUP.md with installation instructions
    const setupInstructions = generateSetupInstructions(result);
    zip.file("SETUP.md", setupInstructions);

    // Generate the zip file
    const blob = await zip.generateAsync({ type: "blob" });

    // Trigger download
    const link = document.createElement("a");
    link.href = URL.createObjectURL(blob);
    link.download = `${projectName}.zip`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    // Clean up
    URL.revokeObjectURL(link.href);
  } catch (error) {
    console.error("Error exporting shadcn project:", error);
    throw new Error("Failed to export project. Please try again.");
  }
}

